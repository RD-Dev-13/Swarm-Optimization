"""
Task Generator Module for Cloud Resource Scheduling Simulation.

Generates synthetic computational jobs with realistic CPU demands, chronological arrival
times, priorities, memory footprints, and distinct workload profiles (light, normal, heavy, bursty).
Designed for reproducible cloud scheduling experiments.
"""

from dataclasses import dataclass, asdict
from pathlib import Path
from typing import List, Optional, Union
import numpy as np
import pandas as pd

from config import (
    WORKLOAD_PROFILES,
    DEFAULT_NUM_TASKS,
    MIN_NUM_TASKS,
    MAX_NUM_TASKS,
    DEFAULT_RANDOM_SEED,
    MIN_PRIORITY,
    MAX_PRIORITY,
    MEMORY_CHOICES_MB,
)


@dataclass
class Task:
    """
    Represents a computational cloud task submitted to the virtualized infrastructure.

    Attributes:
        task_id: Unique string identifier (e.g., 'T001').
        cpu_demand_mi: Required computational workload in Million Instructions (MI).
        arrival_time: Submission timestamp in seconds (chronological).
        priority: Task priority level (1 = lowest, 5 = critical).
        memory_mb: Memory footprint requirement in megabytes.
        workload_type: Name of the workload distribution profile used to generate the task.
    """
    task_id: str
    cpu_demand_mi: float
    arrival_time: float
    priority: int
    memory_mb: float
    workload_type: str

    def to_dict(self) -> dict:
        """Serialize task attributes to a standard dictionary."""
        return asdict(self)

    def __repr__(self) -> str:
        return (
            f"Task(id='{self.task_id}', cpu={self.cpu_demand_mi:.1f}MI, "
            f"arrival={self.arrival_time:.2f}s, priority={self.priority}, "
            f"mem={self.memory_mb:.0f}MB, type='{self.workload_type}')"
        )


class TaskGenerator:
    """
    Synthetic task generation engine for discrete-event cloud scheduling.

    Supports multiple workload distributions:
      - 'light': Low CPU demand (1,000–5,000 MI), 0.5s mean inter-arrival.
      - 'normal': Moderate CPU demand (2,000–10,000 MI), 1.0s mean inter-arrival.
      - 'heavy': High CPU demand (8,000–20,000 MI), 1.5s mean inter-arrival.
      - 'bursty': Clustered rapid arrivals (2,000–15,000 MI) simulating peak load surges.

    Guarantees:
      - Chronological arrival times: t[i] >= t[i-1] >= 0.0.
      - Deterministic reproducibility when initialized with identical random seeds.
      - Strict input validation against invalid task counts or workload profiles.
    """

    def __init__(self, seed: Optional[int] = DEFAULT_RANDOM_SEED):
        """
        Initialize the TaskGenerator with an optional random seed.

        Args:
            seed: Non-negative integer for deterministic pseudo-random number generation.
                  If None, a non-deterministic seed is generated by the OS.
        """
        self.seed = seed
        self._rng: np.random.Generator = np.random.default_rng(seed)
        self.last_generated_tasks: List[Task] = []

    def set_seed(self, seed: Optional[int]) -> None:
        """
        Reset the internal random number generator state with a new seed.

        Args:
            seed: Non-negative integer seed or None.
        """
        if seed is not None and (not isinstance(seed, (int, np.integer)) or seed < 0):
            raise ValueError(f"Random seed must be a non-negative integer or None, got: {seed}")
        self.seed = seed
        self._rng = np.random.default_rng(seed)

    def _validate_inputs(self, num_tasks: int, workload_type: str) -> str:
        """
        Validate task count bounds and workload scenario name.

        Args:
            num_tasks: Number of tasks requested.
            workload_type: Target workload scenario name.

        Returns:
            Normalized lowercase workload_type string.

        Raises:
            TypeError: If num_tasks is not an integer.
            ValueError: If num_tasks is out of [MIN_NUM_TASKS, MAX_NUM_TASKS]
                        or workload_type is not recognized.
        """
        if not isinstance(num_tasks, (int, np.integer)):
            raise TypeError(f"num_tasks must be an integer, got {type(num_tasks).__name__}")

        if not (MIN_NUM_TASKS <= num_tasks <= MAX_NUM_TASKS):
            raise ValueError(
                f"Task count must be between {MIN_NUM_TASKS} and {MAX_NUM_TASKS}, "
                f"requested: {num_tasks}"
            )

        norm_type = str(workload_type).strip().lower()
        if norm_type not in WORKLOAD_PROFILES:
            valid_types = list(WORKLOAD_PROFILES.keys())
            raise ValueError(
                f"Unknown workload type '{workload_type}'. Valid options are: {valid_types}"
            )

        return norm_type

    def generate_cpu_demand(self, count: int, workload_type: str = "normal") -> np.ndarray:
        """
        Generate CPU computational demands in Million Instructions (MI).

        Uses a uniform distribution bounded by the workload profile's min and max thresholds.

        Args:
            count: Number of tasks.
            workload_type: Workload profile identifier ('light', 'normal', 'heavy', 'bursty').

        Returns:
            1D NumPy array of CPU demands rounded to one decimal place.
        """
        norm_type = self._validate_inputs(count, workload_type)
        profile = WORKLOAD_PROFILES[norm_type]
        demands = self._rng.uniform(profile.cpu_min_mi, profile.cpu_max_mi, size=count)
        return np.round(demands, 1)

    def generate_arrival_times(self, count: int, workload_type: str = "normal") -> np.ndarray:
        """
        Generate chronological arrival times in seconds starting from t = 0.0.

        For standard workloads ('light', 'normal', 'heavy'), inter-arrival times are drawn
        from an exponential distribution (Poisson arrival process):
            Δt ~ Exponential(mean = beta)
            t[i] = t[i-1] + Δt[i], with t[0] = 0.0

        For 'bursty' workloads, arrival times are modeled via a two-state Markov-modulated
        burst process:
            - Burst state (high frequency surge): Δt ~ Exponential(mean = 0.05s)
            - Quiescent state (calm gaps): Δt ~ Exponential(mean = 2.0s)
            Alternating burst clusters simulate peak cloud traffic waves.

        Args:
            count: Number of tasks.
            workload_type: Workload profile identifier.

        Returns:
            1D NumPy array of non-decreasing arrival timestamps rounded to two decimal places.
        """
        norm_type = self._validate_inputs(count, workload_type)

        if count == 1:
            return np.array([0.0], dtype=float)

        if norm_type == "bursty":
            # Two-state burst generation: cluster size between 3 and 6 tasks
            inter_arrivals = [0.0]  # First task at t=0
            current_tasks = 1
            in_burst = True
            cluster_rem = self._rng.integers(3, 7)

            while current_tasks < count:
                if in_burst:
                    # Rapid arrival inside surge cluster
                    delta = float(self._rng.exponential(scale=0.06))
                    delta = max(0.01, min(delta, 0.20))  # bounded tight interval
                    inter_arrivals.append(delta)
                    cluster_rem -= 1
                    if cluster_rem <= 0:
                        in_burst = False
                else:
                    # Calmer gap before next surge
                    delta = float(self._rng.exponential(scale=2.2))
                    delta = max(1.0, min(delta, 5.0))
                    inter_arrivals.append(delta)
                    in_burst = True
                    cluster_rem = self._rng.integers(3, 7)
                current_tasks += 1

            arrivals = np.cumsum(inter_arrivals)
        else:
            profile = WORKLOAD_PROFILES[norm_type]
            # First task arrives at t=0, subsequent tasks follow exponential inter-arrival
            deltas = self._rng.exponential(scale=profile.mean_inter_arrival_sec, size=count - 1)
            inter_arrivals = np.insert(deltas, 0, 0.0)
            arrivals = np.cumsum(inter_arrivals)

        return np.round(arrivals, 2)

    def generate_priorities(self, count: int) -> np.ndarray:
        """
        Generate task priorities from 1 (lowest) to 5 (critical).

        Distribution reflects realistic cloud traffic:
        - Priority 1 (Low): 15%
        - Priority 2 (Normal): 45%
        - Priority 3 (Medium): 25%
        - Priority 4 (High): 10%
        - Priority 5 (Critical): 5%

        Args:
            count: Number of tasks.

        Returns:
            1D NumPy array of integer priorities.
        """
        priorities = np.arange(MIN_PRIORITY, MAX_PRIORITY + 1)
        probabilities = [0.15, 0.45, 0.25, 0.10, 0.05]
        return self._rng.choice(priorities, size=count, p=probabilities)

    def generate_memory(
        self,
        count: int,
        cpu_demands: Optional[np.ndarray] = None
    ) -> np.ndarray:
        """
        Generate memory requirements in megabytes.

        Memory tiers are chosen from standard cloud footprints (512, 1024, 2048, 4096 MB).
        If CPU demands are provided, higher CPU tasks are probabilistically steered toward
        larger memory tiers.

        Args:
            count: Number of tasks.
            cpu_demands: Optional CPU demand array to correlate memory with compute intensity.

        Returns:
            1D NumPy array of memory sizes in MB.
        """
        tiers = np.array(MEMORY_CHOICES_MB, dtype=float)

        if cpu_demands is not None and len(cpu_demands) == count:
            # Correlated assignment: normalize CPU demand to index tiers
            min_cpu = float(np.min(cpu_demands))
            max_cpu = float(np.max(cpu_demands))
            spread = max(max_cpu - min_cpu, 1.0)
            normalized = (cpu_demands - min_cpu) / spread  # [0, 1]

            memory_list = []
            for norm_val in normalized:
                # Base index biased by CPU demand plus small random noise
                bias_idx = int(np.clip(np.round(norm_val * (len(tiers) - 1) + self._rng.uniform(-0.5, 0.5)), 0, len(tiers) - 1))
                memory_list.append(tiers[bias_idx])
            return np.array(memory_list, dtype=float)

        # Uniform choice across standard tiers
        return self._rng.choice(tiers, size=count)

    def generate_tasks(
        self,
        num_tasks: Optional[int] = DEFAULT_NUM_TASKS,
        workload_type: Optional[str] = "normal"
    ) -> List[Task]:
        """
        Generate a complete synthetic task batch meeting all simulation constraints.

        Args:
            num_tasks: Number of tasks to generate (default 20, max 50).
            workload_type: Workload profile ('light', 'normal', 'heavy', 'bursty').

        Returns:
            List of Task instances sorted chronologically by arrival time.
        """
        target_count = DEFAULT_NUM_TASKS if num_tasks is None else num_tasks
        target_workload = "normal" if workload_type is None else workload_type

        norm_type = self._validate_inputs(target_count, target_workload)

        cpu_demands = self.generate_cpu_demand(target_count, norm_type)
        arrival_times = self.generate_arrival_times(target_count, norm_type)
        priorities = self.generate_priorities(target_count)
        memory_reqs = self.generate_memory(target_count, cpu_demands)

        tasks: List[Task] = []
        for i in range(target_count):
            task_id = f"T{i + 1:03d}"
            tasks.append(
                Task(
                    task_id=task_id,
                    cpu_demand_mi=float(cpu_demands[i]),
                    arrival_time=float(arrival_times[i]),
                    priority=int(priorities[i]),
                    memory_mb=float(memory_reqs[i]),
                    workload_type=norm_type,
                )
            )

        # Tasks are naturally generated with non-decreasing arrival times;
        # ensure strict chronological sort as an invariant.
        tasks.sort(key=lambda t: t.arrival_time)
        self.last_generated_tasks = tasks
        return tasks

    def to_dataframe(self, tasks: Optional[List[Task]] = None) -> pd.DataFrame:
        """
        Convert task instances into a structured pandas DataFrame.

        Args:
            tasks: List of Task objects. If None, uses last_generated_tasks.

        Returns:
            pd.DataFrame with columns:
                ['task_id', 'cpu_demand_mi', 'arrival_time', 'priority', 'memory_mb', 'workload_type']
        """
        task_list = tasks if tasks is not None else self.last_generated_tasks
        if not task_list:
            return pd.DataFrame(
                columns=[
                    "task_id",
                    "cpu_demand_mi",
                    "arrival_time",
                    "priority",
                    "memory_mb",
                    "workload_type",
                ]
            )

        records = [t.to_dict() for t in task_list]
        df = pd.DataFrame(records)
        df["priority"] = df["priority"].astype(int)
        df["cpu_demand_mi"] = df["cpu_demand_mi"].astype(float)
        df["arrival_time"] = df["arrival_time"].astype(float)
        df["memory_mb"] = df["memory_mb"].astype(float)
        return df

    def save_to_csv(
        self,
        filepath: Union[str, Path],
        tasks: Optional[List[Task]] = None
    ) -> str:
        """
        Export generated tasks to a CSV file.

        Args:
            filepath: Destination path string or Path object.
            tasks: Optional list of Task objects. If None, uses last_generated_tasks.

        Returns:
            Absolute file path of the saved CSV.

        Raises:
            ValueError: If no tasks are available to export.
        """
        df = self.to_dataframe(tasks)
        if df.empty:
            raise ValueError("No tasks available to export. Generate tasks before saving.")

        target_path = Path(filepath).resolve()
        target_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(target_path, index=False)
        return str(target_path)


